#!/usr/bin/env node
// High contrast from the system setting (OpenSpec website-accessibility "High contrast
// from the system setting"; design D3). The bundle's high-contrast token blocks are
// selected by [data-contrast="high"], an attribute no page can set without JavaScript,
// so the build writes them once more inside `@media (prefers-contrast: more)` into
// src/styles/contrast.generated.css: a transform of the pinned bundle's own text, never
// a hand copy. A bundle without the blocks yields an empty stylesheet, and the statement
// says so. Runs in `prebuild`.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

/** The body of the block that follows `selector`, or null when the stylesheet has none. */
function block(css, selector) {
  const at = css.indexOf(selector);
  if (at < 0) return null;
  const open = css.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
  }
  return null;
}

/** The high-contrast stylesheet for a bundle's tokens.css: light and dark overrides under the system's request for more contrast, or a note when the bundle has none. */
export function highContrastCss(tokensCss, version = '') {
  const light = block(tokensCss, 'html:root[data-contrast="high"], html[data-contrast="high"] [data-theme="light"] {');
  const dark = block(tokensCss, 'html:root[data-contrast="high"][data-theme="dark"], html[data-contrast="high"] [data-theme="dark"] {');
  if (!light || !dark) return `/* Generated by scripts/high-contrast.mjs: the pinned bundle ${version} carries no high-contrast tokens; nothing to apply. */\n`;
  const trim = (body) => body.split('\n').map((l) => l.trim()).filter(Boolean).map((l) => `    ${l}`).join('\n');
  return `/* Generated by scripts/high-contrast.mjs from the pinned bundle ${version}: the app's high-contrast
   tokens under the system's request for more contrast (OpenSpec website-accessibility). Do not edit. */
@media (prefers-contrast: more) {
  :root, [data-theme="light"] {
${trim(light)}
  }
  @media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
${trim(dark)}
    }
  }
  :root[data-theme="dark"], [data-theme="dark"] {
${trim(dark)}
  }
}
`;
}

/** Whether a bundle's tokens.css carries the override. */
export const hasHighContrast = (tokensCss) => highContrastCss(tokensCss).includes('@media (prefers-contrast: more)');

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const dir = process.env.BUNDLE_DIR ? path.resolve(process.env.BUNDLE_DIR) : path.join(ROOT, '.bundle');
  const tokens = fs.readFileSync(path.join(dir, 'tokens/tokens.css'), 'utf8');
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  const out = highContrastCss(tokens, manifest.tag ?? (String(manifest.version).startsWith('v') ? manifest.version : `v${manifest.version}`));
  const file = path.join(ROOT, 'src/styles/contrast.generated.css');
  fs.writeFileSync(file, out);
  console.log(`high contrast: ${hasHighContrast(tokens) ? 'the bundle carries the override; written' : 'not in this bundle; empty stylesheet written'} (${path.relative(ROOT, file)})`);
}
